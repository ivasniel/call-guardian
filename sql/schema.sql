CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 name VARCHAR(120) NOT NULL, phone_e164 VARCHAR(20) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS phone_numbers (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 user_id BIGINT UNSIGNED NOT NULL, telnyx_e164 VARCHAR(20) NOT NULL UNIQUE,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS contacts (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 user_id BIGINT UNSIGNED NOT NULL, display_name VARCHAR(180) NOT NULL,
 phone_e164 VARCHAR(20) NOT NULL, priority BOOLEAN DEFAULT FALSE,
 classification ENUM('TRUSTED','NORMAL','BLOCKED') NOT NULL DEFAULT 'NORMAL',
 UNIQUE KEY uq_user_phone (user_id,phone_e164),
 FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS calls (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 user_id BIGINT UNSIGNED NOT NULL,
 call_control_id VARCHAR(255) NOT NULL UNIQUE,
 from_e164 VARCHAR(20), to_e164 VARCHAR(20), contact_id BIGINT UNSIGNED NULL,
 status ENUM('INITIATED','ANSWERED','GATHERING','MESSAGE','HUNG_UP','ERROR') DEFAULT 'INITIATED',
 decision ENUM('KNOWN','UNKNOWN','BLOCKED','URGENT','NORMAL','SPAM') DEFAULT 'UNKNOWN',
 caller_digits VARCHAR(8), started_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 ended_at TIMESTAMP NULL,
 FOREIGN KEY (user_id) REFERENCES users(id),
 FOREIGN KEY (contact_id) REFERENCES contacts(id)
);
CREATE TABLE IF NOT EXISTS webhook_events (
 event_id VARCHAR(100) PRIMARY KEY, event_type VARCHAR(100) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
